/**
 * Writes ready-made WebP sizes of the site's own pictures, and lib/sizedImages.ts,
 * the list components/ui/Image reads to show them. Pictures listed there never
 * pass through Vercel's image optimiser, whose monthly allowance ran out in
 * October 2026 (every picture it had not already made came back blank).
 *
 * Each <name>.jpg in the folders below gets <folder>/sized/<name>-<width>.webp
 * at 128, 384, 640, 960 and 1280 px wide, never wider than the original (whose
 * own width is always one of them). Pictures whose sizes are newer than the
 * original are left alone, so a run only does what changed.
 *
 *   npm i --no-save sharp                  # once
 *   node scripts/image-sizes.mjs
 *
 * Run it after adding or replacing a picture in these folders. A re-shot design
 * picture also gets a version bump in lib/templateMedia.ts.
 */
import sharp from 'sharp'
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'fs'

const ROOT = new URL('../', import.meta.url).pathname
const FOLDERS = ['templates', 'templates/phone', 'occasions', 'blog']
const WIDTHS = [128, 384, 640, 960, 1280]

const list = {}
for (const folder of FOLDERS) {
  const dir = `${ROOT}public/${folder}/`
  mkdirSync(`${dir}sized`, { recursive: true })
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.jpg')).sort()) {
    const name = file.slice(0, -'.jpg'.length)
    const { width: full } = await sharp(dir + file).metadata()
    const widths = [...WIDTHS.filter((w) => w < full), Math.min(full, WIDTHS[WIDTHS.length - 1])]
    const changed = statSync(dir + file).mtimeMs
    let made = 0
    for (const width of widths) {
      const out = `${dir}sized/${name}-${width}.webp`
      if (existsSync(out) && statSync(out).mtimeMs >= changed) continue
      await sharp(dir + file).resize({ width, withoutEnlargement: true }).webp({ quality: 74, effort: 6 }).toFile(out)
      made++
    }
    list[`/${folder}/${file}`] = widths
    if (made) console.log(`${folder}/${file}: ${made} made`)
  }
}

writeFileSync(
  `${ROOT}lib/sizedImages.ts`,
  `/**
 * GENERATED by scripts/image-sizes.mjs — do not edit by hand.
 *
 * The site's own pictures that have ready-made WebP sizes beside them (in a
 * \`sized\` folder), and those widths. components/ui/Image shows these files
 * instead of sending the pictures through Vercel's image optimiser.
 */

export const SIZED_IMAGES: Record<string, readonly number[]> = {
${Object.entries(list).map(([path, widths]) => `  '${path}': [${widths.join(', ')}],`).join('\n')}
}
`,
)
console.log(`${Object.keys(list).length} pictures listed in lib/sizedImages.ts`)
