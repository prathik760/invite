/**
 * Writes lib/designPlaceholders.ts: for each design picture in public/templates,
 * a 12×15 WebP (a few hundred bytes, inlined as a data URL) that the homepage
 * paints behind the real picture. Until the picture arrives (lazy loading, a
 * slow connection), a card shows a soft blur of its own artwork, never an
 * empty tile.
 *
 *   npm i --no-save sharp                  # once
 *   node scripts/home-placeholders.mjs
 *
 * Run it after adding or replacing a design picture (as for image-sizes.mjs).
 */
import sharp from 'sharp'
import { readdirSync, writeFileSync } from 'fs'

const ROOT = new URL('../', import.meta.url).pathname
const dir = `${ROOT}public/templates/`
const out = {}
for (const file of readdirSync(dir).filter((f) => f.endsWith('.jpg')).sort()) {
  const buf = await sharp(dir + file).resize(12, 15, { fit: 'cover', position: 'top' }).webp({ quality: 50 }).toBuffer()
  out[file.slice(0, -'.jpg'.length)] = `data:image/webp;base64,${buf.toString('base64')}`
}
const body = Object.entries(out).map(([k, v]) => `  '${k}': '${v}',`).join('\n')
writeFileSync(
  `${ROOT}lib/designPlaceholders.ts`,
  `/**\n * GENERATED by scripts/home-placeholders.mjs — do not edit by hand.\n *\n * A tiny blurred stand-in for each design picture, painted behind it until it\n * loads (see designPlaceholder below).\n */\n\nconst PLACEHOLDERS: Record<string, string> = {\n${body}\n}\n\n/** The CSS that paints a design's blur behind its picture, or nothing for an unknown id. */\nexport function designPlaceholder(templateId: string): { backgroundImage?: string; backgroundSize?: string; backgroundPosition?: string } {\n  const url = PLACEHOLDERS[templateId]\n  return url ? { backgroundImage: \`url(\${url})\`, backgroundSize: 'cover', backgroundPosition: 'top' } : {}\n}\n`,
)
console.log(`${Object.keys(out).length} placeholders, ${Math.round(JSON.stringify(out).length / 1024)} KB in lib/designPlaceholders.ts`)
